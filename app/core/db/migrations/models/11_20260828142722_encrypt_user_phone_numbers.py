from tortoise import BaseDBAsyncClient

from app.core.phone_encryption import decrypt_phone_number, encrypt_phone_number

RUN_IN_TRANSACTION = True

_SELECT_PHONES_SQL = "SELECT `id`, `phone` FROM `user` WHERE `phone` IS NOT NULL"
_UPDATE_PHONE_SQL = "UPDATE `user` SET `phone`=%s WHERE `id`=%s"
_FERNET_TOKEN_PREFIX = "gAAAAA"


async def upgrade(db: BaseDBAsyncClient) -> str:
    if db is None:
        return "SELECT 1;"

    rows = await db.execute_query_dict(_SELECT_PHONES_SQL)
    updates: list[tuple[str, int]] = []
    for row in rows:
        phone = row["phone"]
        if phone.startswith(_FERNET_TOKEN_PREFIX):
            # 현재 키로 복호화되지 않으면 다른 키의 암호문일 수 있으므로
            # 이중 암호화하지 않고 전체 마이그레이션을 중단한다.
            decrypt_phone_number(phone)
            continue
        updates.append((encrypt_phone_number(phone), row["id"]))

    if updates:
        await db.execute_many(_UPDATE_PHONE_SQL, updates)
    return "SELECT 1;"


async def downgrade(db: BaseDBAsyncClient) -> str:
    if db is None:
        return "SELECT 1;"

    rows = await db.execute_query_dict(_SELECT_PHONES_SQL)
    updates = [
        (decrypt_phone_number(row["phone"]), row["id"])
        for row in rows
        if row["phone"].startswith(_FERNET_TOKEN_PREFIX)
    ]
    if updates:
        await db.execute_many(_UPDATE_PHONE_SQL, updates)
    return "SELECT 1;"


