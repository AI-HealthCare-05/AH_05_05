async def upgrade(db: BaseDBAsyncClient) -> str:
    # NOT NULL 컬럼을 한 번에 추가하면 기존 행 때문에 실패한다(sql_mode=STRICT_TRANS_TABLES).
    # nullable 로 추가 -> 행마다 서로 다른 난수 채우기 -> NOT NULL 로 조인다.
    #
    # 백필 값은 계정마다 달라야 한다. 같은 값을 넣으면 세션 무효화가 계정 단위로
    # 동작하지 않는다. 기존 관리자의 리프레시 토큰에는 sid 클레임이 없으므로
    # 이 마이그레이션 이후 모두 재로그인해야 한다(의도된 동작).
    return """
        ALTER TABLE `admin` ADD `session_salt` VARCHAR(32) NULL;
        UPDATE `admin` SET `session_salt` = MD5(CONCAT(RAND(), `id`, NOW(6))) WHERE `session_salt` IS NULL;
        ALTER TABLE `admin` MODIFY `session_salt` VARCHAR(32) NOT NULL;"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    return """
        ALTER TABLE `admin` DROP COLUMN `session_salt`;"""


